"""Writes src/assets/brand/bison-pose.css: the moving parts' shapes and
joints (in pixels of the 384 px poses in src/assets/brand/mascot/) plus
the animations. Run from the repo root after changing either:

    python scripts/gen-bison-css.py
"""

W = 384.0


def p(v):
    return f"{v / W * 100:.1f}%"


def poly(points):
    return "polygon(" + ", ".join(f"{p(x)} {p(y)}" for x, y in points) + ")"


def holes(*shapes):
    """The whole image minus each shape (evenodd; joined through 0 0)"""
    pts = [(0, 0), (W, 0), (W, W), (0, W), (0, 0)]
    for shape in shapes:
        pts += shape + [shape[0], (0, 0)]
    return "polygon(evenodd, " + ", ".join(f"{p(x)} {p(y)}" for x, y in pts) + ")"


def at(x, y):
    return f"{p(x)} {p(y)}"


import math

# Heads: an ellipse mask, solid to 80% of its radius and gone at 100%, so
# the cut through the hump blends into the fur. (center, radii)
HEAD_STAND = ((292, 182), (135, 160))
HEAD_CARRY = ((292, 180), (135, 128))
HEAD_REST = ((290, 188), (128, 132))


def head_mask(head):
    (cx, cy), (rx, ry) = head
    return (
        f"radial-gradient(ellipse {p(rx)} {p(ry)} at {p(cx)} {p(cy)}, "
        "#000 80%, transparent 100%)"
    )


def ellipse(head, scale=0.76, n=24):
    """The body's hole for a head: inside the head's solid part"""
    (cx, cy), (rx, ry) = head
    return [
        (cx + rx * scale * math.cos(2 * math.pi * i / n), cy + ry * scale * math.sin(2 * math.pi * i / n))
        for i in range(n)
    ]


# Other parts: hard shapes, each a little larger than its hole
TAIL_HANG = [(0, 175), (36, 175), (40, 262), (0, 262)]
TAIL_CURL = [(0, 100), (50, 100), (50, 172), (0, 172)]
BADGE = [(56, 28), (130, 28), (130, 100), (56, 100)]
CRATES = [(70, 70), (194, 70), (194, 178), (70, 178)]
CRATES_HOLE = [(76, 76), (188, 76), (188, 160), (76, 160)]

NECK = at(238, 240)
NECK_REST = at(238, 252)

rules = f"""
/* Shapes: generated from the 384 px poses (see the header) */
.bison[data-pose='rest'] .bp-base {{ clip-path: {holes(ellipse(HEAD_REST))}; }}
.bison[data-pose='rest'] .bp-head {{ -webkit-mask-image: {head_mask(HEAD_REST)}; mask-image: {head_mask(HEAD_REST)}; transform-origin: {NECK_REST}; }}
.bison[data-pose='rest'] .bp-stand {{ clip-path: {holes(BADGE)}; }}

.bison[data-pose='wait'] .bp-base {{ clip-path: {holes(ellipse(HEAD_STAND), TAIL_HANG, BADGE)}; }}
.bison[data-pose='wait'] .bp-head {{ -webkit-mask-image: {head_mask(HEAD_STAND)}; mask-image: {head_mask(HEAD_STAND)}; transform-origin: {NECK}; }}
.bison[data-pose='wait'] .bp-tail {{ clip-path: {poly(TAIL_HANG)}; transform-origin: {at(34, 178)}; }}
.bison[data-pose='wait'] .bp-badge {{ clip-path: {poly(BADGE)}; transform-origin: {at(93, 64)}; }}

.bison[data-pose='carry'] .bp-base {{ clip-path: {holes(ellipse(HEAD_CARRY), TAIL_HANG, CRATES_HOLE)}; }}
.bison[data-pose='carry'] .bp-head {{ -webkit-mask-image: {head_mask(HEAD_CARRY)}; mask-image: {head_mask(HEAD_CARRY)}; transform-origin: {NECK}; }}
.bison[data-pose='carry'] .bp-tail {{ clip-path: {poly(TAIL_HANG)}; transform-origin: {at(34, 172)}; }}
.bison[data-pose='carry'] .bp-crates {{ clip-path: {poly(CRATES)}; transform-origin: {at(132, 168)}; }}

.bison[data-pose='done'] .bp-base {{ clip-path: {holes(ellipse(HEAD_STAND), TAIL_CURL, BADGE)}; }}
.bison[data-pose='done'] .bp-head {{ -webkit-mask-image: {head_mask(HEAD_STAND)}; mask-image: {head_mask(HEAD_STAND)}; transform-origin: {NECK}; }}
.bison[data-pose='done'] .bp-tail {{ clip-path: {poly(TAIL_CURL)}; transform-origin: {at(46, 168)}; }}
.bison[data-pose='done'] .bp-badge {{ clip-path: {poly(BADGE)}; transform-origin: {at(93, 66)}; }}
"""

HEADER = """/*
 * The bison, alive (BisonPose.tsx). Each pose image is stacked: the body,
 * and copies cut to the parts that move (head, tail, crates, the badge),
 * each turning a few degrees about its joint. The body leaves the parts
 * out, and each part is a little larger than the hole it fills, so a turn
 * never shows a gap. The head's edge is feathered (a mask, not a cut), so
 * where it meets the hump there's no seam. Coordinates come from the
 * 384 px poses in mascot/. Generated by scripts/gen-bison-css.py: edit
 * that and run it, not this file.
 *
 * Each pose has several loops of different lengths, so the moments line
 * up differently each time ("sometimes"):
 * - rest: breathes; dozes off and looks up (9 s); gets up, stretches and
 *   lies down again (24 s, crossfading to the standing pose; first after
 *   about 4 s)
 * - wait: shifts its weight (7 s); lifts its head to look at you, then
 *   nods (5 s); swishes its tail (3.7 s); the ! pulses
 * - carry: walks with a bob, its head nodding each step, the crates
 *   rocking half a step behind, the tail swaying
 * - done: the check pops in, two nods, the tail flicks
 * It holds still (lying down when at rest) under the system's "reduce
 * motion", unless Settings › Appearance says Always
 * (`data-bison-motion` on <html>, `lib/bison-motion.ts`); Never always.
 */
.bison {
  position: relative;
  display: inline-block;
  flex: none;
}
.bison .bp-group,
.bison .bp-part {
  position: absolute;
  inset: 0;
  width: 100%;
  height: 100%;
}
.bison .bp-part {
  display: block;
  user-select: none;
  pointer-events: none;
}
.bison .bp-group,
.bison .bp-head,
.bison .bp-tail,
.bison .bp-crates,
.bison .bp-badge,
.bison .bp-stand {
  will-change: transform, opacity;
}
"""

